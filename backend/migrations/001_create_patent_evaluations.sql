CREATE TABLE IF NOT EXISTS public.patent_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_type VARCHAR(32) NOT NULL,
    dataset_version VARCHAR(32) NOT NULL DEFAULT '0.2.0',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    summary_json TEXT NOT NULL,
    result_json TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_patent_evaluations_evaluation_type
    ON public.patent_evaluations (evaluation_type);
CREATE INDEX IF NOT EXISTS ix_patent_evaluations_created_at
    ON public.patent_evaluations (created_at DESC);
